def strip_variants(text):
    """(текст без просьбы о вариантах, просили ли варианты, «по тексту»?).
    over_text=True — сказано «варианты по тексту», переписываем строго надиктованное."""
    text = (text or "").strip()
    m = _VARIANTS_RX.search(text)
    if not m:
        return text, False, False
    body = text[:m.start()].rstrip().rstrip(",;:")
    if not body:
        return text, False, False   # «Предложи варианты» без текста — это обычная речь
    over_text = "текст" in m.group(0).lower()
    return body, True, over_text


def build_variants_messages(text, cmd, count=VARIANTS_COUNT):
    """Попросить у модели несколько разных вариантов одним запросом, ответ — JSON-массив строк."""
    rules = RUDE_RULES if cmd.get("rude") else RULES
    task = (f"{cmd['instruction']}\n\nДай ровно {count} разных варианта: они должны отличаться "
            f"формулировками и подачей, но выполнять одну и ту же задачу. Верни только JSON-массив "
            f"из {count} строк и ничего больше, например [\"первый\", \"второй\", \"третий\"].")
    return [{"role": "system", "content": rules},
            {"role": "user", "content": f"Задача: {task}\nТекст: {text}\nОтвет:"}]


def parse_variants(raw, count=VARIANTS_COUNT):
    """Ответ модели → список вариантов. JSON-массив, иначе строки или нумерованный список."""
    import json

    t = humanize(raw)
    start, end = t.find("["), t.rfind("]")
    if start >= 0 and end > start:
        try:
            items = json.loads(t[start:end + 1])
            got = [humanize(str(i)).strip() for i in items if str(i).strip()]
            if got:
                return got[:count]
        except ValueError:
            pass
    lines = []
    for line in t.splitlines():
        line = re.sub(r"^\s*(?:\d+[.)]|[-*•])\s*", "", line).strip().strip('",')
        if line:
            lines.append(line)
    return lines[:count]


def build_refine_messages(variants, instruction, style="", count=VARIANTS_COUNT):
    """Текущие варианты + голосовая правка → новые варианты. Правка может быть грубой."""
    rude = _is_rude(instruction) or _is_rude(style)
    rules = RUDE_RULES if rude else RULES
    cur = "\n".join(f"{i + 1}. {v}" for i, v in enumerate(variants))
    task = (f"Вот текущие варианты текста:\n{cur}\n\nПользователь просит изменить их так: {instruction}\n"
            f"Примени эту правку ко всем и верни ровно {count} новых варианта JSON-массивом строк, "
            f"без пояснений. Сохрани смысл и факты, меняй только то, о чём просят.")
    return [{"role": "system", "content": rules},
            {"role": "user", "content": task}]
