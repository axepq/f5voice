_END = r"\s*[.!?…]*\s*$"                  # хвостовые знаки после команды
# «сделай в официальном стиле», «напиши официально», «а теперь короче» — глагол-обёртка перед триггером
_VERBS = (r"(?:(?:а\s+)?(?:теперь\s+)?(?:сделай|сделать|напиши|написать|перепиши|переписать|переделай|"
          r"переведи|перевести|давай|пожалуйста)\s+)")
_AFTER_PUNCT = r"(?:^|(?<=[.!?,;:…]))\s*" + _VERBS + r"*(?:это\s+)?"
# Триггер из одного слова («короче», «понятнее», «технически») без знака перед ним — это обычная речь
# («я хочу сказать это короче»); без знака он считается командой только с глаголом-обёрткой.
_LOOSE_MULTI = r"(?:" + _AFTER_PUNCT + r"|\s+" + _VERBS + r"*(?:это\s+)?)"
_LOOSE_SINGLE = r"(?:" + _AFTER_PUNCT + r"|\s+" + _VERBS + r"+(?:это\s+)?)"


def merge_commands(user=None):
    """Встроенные команды плюс пользовательские из config.json: {"триггер|триггер": "инструкция"}.
    Совпадающий триггер пользователя переопределяет встроенный."""
    result = dict(COMMANDS)
    for n, (triggers, instruction) in enumerate((user or {}).items(), 1):
        if not isinstance(triggers, str) or not isinstance(instruction, str):
            continue
        mine = {t.strip().lower() for t in triggers.split("|") if t.strip()}
        for key, (their, _) in list(result.items()):
            rest = [t for t in their.split("|") if t.strip().lower() not in mine]
            if len(rest) != len(their.split("|")):
                if rest:
                    result[key] = ("|".join(rest), result[key][1])
                else:
                    del result[key]
        if mine:
            result[f"user{n}"] = ("|".join(sorted(mine)), instruction.strip())
    return result


def _fixed(text, commands):
    """Фиксированная команда в хвосте: (тело, команда) или None."""
    for key, (triggers, instruction) in commands.items():
        words = [t.strip() for t in triggers.split("|") if t.strip()]
        # без знака перед собой допустимы только «…стиль/стилем»: «на английском», «исправь ошибки»
        # в конце обычной фразы встречаются и без команды
        multi = "|".join(re.escape(t) for t in words if " " in t and "стил" in t)
        single = "|".join(re.escape(t) for t in words if not (" " in t and "стил" in t))
        alts = []
        if multi:
            alts.append(_LOOSE_MULTI + r"(?P<m>" + multi + r")")
        if single:
            alts.append(_LOOSE_SINGLE + r"(?P<s>" + single + r")")
        m = re.search(r"(?:" + "|".join(alts) + r")" + _END, text, flags=re.IGNORECASE)
        if m:
            body = text[:m.start()].rstrip().rstrip(",;:")
            if body:
                title = (m.groupdict().get("m") or m.groupdict().get("s")).lower()
                return body, {"key": key, "title": title, "instruction": instruction, "rude": _is_rude(instruction)}
    return None


# Свободный/шаблонный стиль, названный в конце фразы. Две формы:
#   имя ПЕРЕД словом стиль: «сделай в юмористичном стиле», «поэтичным стилем»
#   имя ПОСЛЕ слова стиль:  «стиль официальный», «стиль текста юмористический», «в стиле деловой»
# Нужен глагол-обёртка или своё предложение перед оборотом, иначе «мне нравится стиль работы» сработает.
_STYLE_STOP = {"этом", "таком", "том", "каком", "своём", "своем", "любом", "разном", "одном",
               "хорошем", "плохом", "нашем", "вашем", "прежнем", "живом", "свободном",
               "работы", "жизни", "общения", "руководства", "управления", "речи", "письма", "текста"}
_STYLE_ANCHOR = (r"(?:(?<=[.!?…])\s*" + _VERBS + r"*(?:это\s+)?"
                 r"|(?:(?<=[.!?,;:…])\s*|\s+)" + _VERBS + r"+(?:это\s+)?)")
_STYLE_NAME = r"(?P<x>[а-яё][а-яё-]*(?:\s+[а-яё][а-яё-]*){0,2})"
_STYLE_BEFORE = re.compile(_STYLE_ANCHOR + r"(?:в\s+)?" + _STYLE_NAME + r"\s+(?:стиле|стилем)" + _END, re.IGNORECASE)
_STYLE_AFTER = re.compile(_STYLE_ANCHOR + r"(?:в\s+)?стил(?:ь|е|я|ем|ём)(?:\s+текста)?\s+" + _STYLE_NAME + _END, re.IGNORECASE)


def _style_cmd(x, commands):
    """Имя стиля → команда: если это шаблонный стиль, берём его; иначе свободный, придуманный на ходу."""
    x = x.strip().rstrip(".!?…").strip()
    words = x.lower().split()
    if not words or words[-1] in _STYLE_STOP or words[0] in _STYLE_STOP:
        return None
    known = _fixed("з. " + x + " стиль", commands) or _fixed("з. " + x, commands)
    if known:
        return known[1]
    return {"key": "free", "title": x[:60], "rude": _is_rude(x),
            "instruction": f"Перепиши текст в стиле: {x}. Сохрани смысл, факты, числа "
                           "и контекст, ничего важного не теряй."}


def _free_style(text, commands):
    """(тело, команда) для «…текст. Сделай в X стиле» или «…текст. Стиль X», иначе None."""
    for rx in (_STYLE_AFTER, _STYLE_BEFORE):
        m = rx.search(text)
        if not m:
            continue
        cmd = _style_cmd(m.group("x"), commands)
        if not cmd:
            continue
        body = text[:m.start()].rstrip().rstrip(",;:")
        if body:
            return body, cmd
    return None


def split_command(text, commands=None, keyword=DEFAULT_KEYWORD):
    """(текст без команды, команда) или (text, None). Команда — только в самом конце
    и только если перед ней есть текст. Ключевое слово проверяется первым: в «команда: короче»
    тело — то, что до ключевого слова, а не до «короче»."""
    text = (text or "").strip()
    commands = commands if commands is not None else COMMANDS
    if keyword:
        kw = re.escape(keyword)
        # после конца предложения — с двоеточием или без; после запятой — только с двоеточием,
        # иначе «Привет, команда, как дела?» уйдёт в модель
        m = re.search(r"(?:(?<=[.!?…])\s*" + kw + r"\s*[:,]?\s+|(?<=[,;:])\s*" + kw + r"\s*:\s*)(?P<i>.{3,})$",
                      text, flags=re.IGNORECASE | re.DOTALL)
        if m:
            body = text[:m.start()].rstrip().rstrip(",;:")
            instruction = m.group("i").strip()
            if body and instruction:
                known = _fixed("x. " + instruction, commands)  # «команда: официально» — это official
                if known:
                    return body, known[1]
                return body, {"key": "free", "title": instruction.rstrip(".!?…").strip()[:60],
                              "instruction": instruction, "rude": _is_rude(instruction)}
    found = _fixed(text, commands)
    if found:
        return found
    free = _free_style(text, commands)  # свободный/шаблонный стиль, названный в конце
    return free if free else (text, None)


