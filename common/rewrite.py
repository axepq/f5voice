VARIANTS_COUNT = 3
# «…текст. Предложи варианты» — просьба показать несколько вариантов вместо одной вставки.
# С глаголом ловим где угодно в конце; голое «варианты» — только отдельным предложением,
# иначе «в чём вариант вопроса» внутри диктовки ложно сработает.
_VARIANTS_VERB = r"(?:предложи|предложить|покажи|показать|дай|давай|накинь|накидай|напиши|составь|сделай|хочу|нужны)\s+"
_VARIANTS_WORD = r"вариант(?:ы|ов|а)?"
# «…по тексту», «…по существующему тексту», «варианты текста» — принудительно переписываем надиктованное
_VARIANTS_OVER = r"(?:\s+(?:текста|по\s+(?:существующему\s+)?тексту|по\s+моему\s+тексту))?"
_VARIANTS_RX = re.compile(
    r"(?:(?<=[.!?,;:…])\s*|\s+)" + _VARIANTS_VERB + _VARIANTS_WORD + _VARIANTS_OVER + _END
    + r"|(?<=[.!?…])\s*" + _VARIANTS_WORD + _VARIANTS_OVER + _END, re.IGNORECASE)

# Стиль не назван: модель сама решает — надиктован готовый текст или описание того, что нужно написать.
